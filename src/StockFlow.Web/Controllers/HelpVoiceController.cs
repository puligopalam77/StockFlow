using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using StockFlow.Web.Help;
using System.Buffers.Binary;

namespace StockFlow.Web.Controllers;

[Authorize, ApiController, Route("api/help/voice")]
public class HelpVoiceController(HelpVoiceService voice) : ControllerBase
{
    [HttpPost, RequestSizeLimit(2_000_000)]
    public async Task<IActionResult> Transcribe(IFormFile audio, CancellationToken cancellation)
    {
        Response.Headers.CacheControl = "no-store";
        if (audio.Length is <= 44 or > 1_920_044) return BadRequest(new { message = "Record a question up to 60 seconds." });
        using var memory = new MemoryStream(); await audio.CopyToAsync(memory, cancellation); var wave = memory.ToArray();
        // Accept exactly the mono 16 kHz PCM format generated by our recorder.
        if (!wave.AsSpan(0, 4).SequenceEqual("RIFF"u8) || BinaryPrimitives.ReadInt32LittleEndian(wave.AsSpan(4)) != wave.Length - 8 || !wave.AsSpan(8, 8).SequenceEqual("WAVEfmt "u8) ||
            BinaryPrimitives.ReadInt32LittleEndian(wave.AsSpan(16)) != 16 || BinaryPrimitives.ReadInt16LittleEndian(wave.AsSpan(20)) != 1 ||
            BinaryPrimitives.ReadInt16LittleEndian(wave.AsSpan(22)) != 1 || BinaryPrimitives.ReadInt32LittleEndian(wave.AsSpan(24)) != 16000 ||
            BinaryPrimitives.ReadInt32LittleEndian(wave.AsSpan(28)) != 32000 || BinaryPrimitives.ReadInt16LittleEndian(wave.AsSpan(32)) != 2 ||
            BinaryPrimitives.ReadInt16LittleEndian(wave.AsSpan(34)) != 16 || !wave.AsSpan(36, 4).SequenceEqual("data"u8) ||
            BinaryPrimitives.ReadInt32LittleEndian(wave.AsSpan(40)) != wave.Length - 44 || (wave.Length - 44) % 2 != 0)
            return BadRequest(new { message = "The recording format is invalid. Record the question again." });
        try { var text = await voice.Transcribe(wave, cancellation); return Ok(new { text }); }
        catch (InvalidOperationException error) { return StatusCode(503, new { message = error.Message }); }
        catch (Exception error) when (error is HttpRequestException or TaskCanceledException) { return StatusCode(503, new { message = "Local speech is unavailable. Please check the speech runtime, then retry your recording." }); }
    }
}
